#!/usr/bin/env python3
"""Turn a firmware binary into a C initialiser list the host can embed.

    tools/mkinc.py in.bin out.inc "source it came from"
"""
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    binary, include, origin = sys.argv[1:]
    data = open(binary, "rb").read()
    with open(include, "w") as out:
        out.write(f"// Generated by build.sh from {origin}. Do not edit.\n")
        for start in range(0, len(data), 16):
            out.write("".join(f"0x{byte:02x}," for byte in data[start:start + 16]) + "\n")


if __name__ == "__main__":
    main()
